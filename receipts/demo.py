"""The baked demo board, read from package data.

`receipts demo` serves this file with the real desk and no network. The board is
generated by an actual run (see README) and is never edited by hand.
"""

from __future__ import annotations

from importlib import resources
import json

from .store import Store


def demo_board() -> dict:
    text = resources.files("receipts").joinpath("data", "demo_board.json").read_text(encoding="utf-8")
    board = json.loads(text)
    required = {"id", "question", "coverage", "sources", "quotes", "themes", "failures"}
    missing = required - set(board)
    if missing:
        raise ValueError(f"demo board is missing: {', '.join(sorted(missing))}")
    return board


def save_demo_board(path: str, board: dict) -> None:
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(board, handle, indent=2, ensure_ascii=False)
        handle.write("\n")


def demo_store() -> Store:
    """A throwaway store for demo exports, so no state dir is required."""
    return Store(":memory:")
